export function canTransition(from: StageName, to: StageName, context: { fixAttempts?: number } = {}): boolean {
  void context;
  if (to === 'FAILED') return from !== 'COMPLETED';
  if (to === 'ABANDONED') return from !== 'COMPLETED' && from !== 'ABANDONED';
  return transitions[from]?.includes(to) ?? false;
}

export type StageTransitionOptions = { plannedStages?: readonly StageName[]; fixAttempts?: number };

/** Evaluate a persisted transition without changing live state. Explicit
 * state-machine edges win; a forward jump is legal only when the immutable
 * pipeline plan contains both stages in order. */
export function evaluateStageTransition(from: StageName, to: StageName, options: StageTransitionOptions = {}) {
  if (from === to) return StateTransitionAuditSchema.parse({ passed: true, blockers: [] });
  if (canTransition(from, to, options)) return StateTransitionAuditSchema.parse({ passed: true, blockers: [] });
  if (['COMPLETED', 'ABANDONED', 'FAILED'].includes(to)) return StateTransitionAuditSchema.parse({ passed: true, blockers: [] });
  const planned = options.plannedStages ?? [];
  const fromIndex = planned.indexOf(from);
  const toIndex = planned.indexOf(to);
  if (fromIndex >= 0 && toIndex > fromIndex) return StateTransitionAuditSchema.parse({ passed: true, blockers: [] });
  return StateTransitionAuditSchema.parse({ passed: false, blockers: [`invalid-transition:${from}->${to}`] });
}

export function evaluateTransitionHistory(historyValue: readonly StateTransitionRecord[], options: StageTransitionOptions = {}) {
  const history = historyValue.map((item) => StateTransitionRecordSchema.parse(item));
  const blockers: string[] = [];
  history.forEach((item, index) => {
    if (index > 0 && history[index - 1]!.to !== item.from) blockers.push(`history-discontinuity:${index}`);
    const costContinuation = item.from === 'ABANDONED'
      && /^cost-cap-authorized:[a-f0-9]{64}$/u.test(item.reason)
      && (options.plannedStages ?? []).includes(item.to)
      && !['ABANDONED', 'COMPLETED'].includes(item.to);
    const result = costContinuation
      ? StateTransitionAuditSchema.parse({ passed: true, blockers: [] })
      : evaluateStageTransition(item.from, item.to, options);
    blockers.push(...result.blockers.map((blocker) => `${index}:${blocker}`));
  });
  return StateTransitionAuditSchema.parse({ passed: blockers.length === 0, blockers: [...new Set(blockers)] });
}
