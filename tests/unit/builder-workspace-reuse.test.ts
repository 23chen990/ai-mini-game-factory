import { mkdir, mkdtemp, readFile, readdir, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { BuilderAgent } from '../../src/agents/index.js';
import { WebLiteRuntimeAdapter } from '../../src/adapters/web-lite.js';
import type { CodexProvider } from '../../src/providers/interfaces.js';
import { GameBlueprintSchema, StyleLockSchema, AssetManifestSchema } from '../../src/schemas/index.js';

const blueprint = GameBlueprintSchema.parse({ schemaVersion: 1, gameId: 'workspace-reuse-fixture', title: 'Workspace reuse fixture', theme: 'orchestration test only', runtime: 'web-lite', template: 'idle-shop-v1', designMode: 'prototype_tournament', targetPlatforms: ['wechat-minigame', 'douyin-minigame', 'taptap-minigame'], concept: 'No game is generated by these tests.', coreLoop: ['observe', 'act', 'settle', 'replay'], content: { productName: 'fixture', customerName: 'fixture', currencyName: 'fixture' }, balance: { startingCurrency: 0, orderReward: 1, baseUpgradeCost: 1 }, preferences: {} });
const styleLock = StyleLockSchema.parse({ schemaVersion: 1, directionId: 'direction_a', direction: { id: 'direction_a', name: 'Fixture', summary: 'Fixture', visualKeywords: ['fixture'], palette: ['#112233'], characterStyle: 'fixture', environmentStyle: 'fixture', uiStyle: 'fixture', iconConcept: 'fixture', forbiddenElements: [], productionComplexity: 'low', previewPrompt: 'fixture' }, kept: [], changes: [], notes: [], lockedAt: '2026-10-19T00:00:00.000Z' });
const assets = AssetManifestSchema.parse({ schemaVersion: 1, provider: 'fixture', assets: ['customer', 'product', 'background', 'upgrade'].map(id => ({ id, kind: 'ui', path: `assets/${id}.svg`, prompt: 'fixture', status: 'generated', sha256: 'fixture' })) });
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))); });

async function setup() {
  const root = await mkdtemp(path.join(tmpdir(), 'builder-reuse-'));
  roots.push(root);
  const workspace = path.join(root, 'workspace/game');
  const assetSource = path.join(root, 'workspace/generated-assets');
  await mkdir(path.dirname(workspace), { recursive: true });
  await mkdir(assetSource);
  const runtime = new WebLiteRuntimeAdapter(process.cwd());
  // Only marker files are used: no template copy, game generation, models or browser runs.
  const create = vi.spyOn(runtime, 'createProject').mockImplementation(async directory => {
    await mkdir(directory, { recursive: true });
    await writeFile(path.join(directory, 'template-marker.txt'), 'initial');
  });
  const apply = vi.spyOn(runtime, 'applyBlueprint').mockResolvedValue();
  const importAssets = vi.spyOn(runtime, 'importAssets').mockResolvedValue();
  const verify = vi.spyOn(runtime, 'verifyProject').mockResolvedValue(['test:passed', 'typecheck:passed']);
  const buildWeb = vi.spyOn(runtime, 'buildWeb').mockImplementation(async directory => {
    const out = path.join(directory, 'dist');
    await mkdir(out, { recursive: true });
    await writeFile(path.join(out, 'index.html'), '<title>Orchestration fixture, not gameplay evidence</title>');
    return out;
  });
  const providerBuild = vi.fn<CodexProvider['build']>().mockResolvedValue({ threadId: 'fixture-thread', verificationMode: 'full', metrics: { provider: 'fixture', model: 'fixture', calls: 1 } });
  const provider: CodexProvider = { build: providerBuild, async fix() { throw new Error('not part of this test'); } };
  const agent = new BuilderAgent(provider, runtime);
  const run = () => agent.run(workspace, blueprint, styleLock, assets, blueprint.template, assetSource);
  return { root, workspace, assetSource, create, apply, importAssets, verify, buildWeb, providerBuild, run };
}

describe('Builder workspace continuation', () => {
  it('continues an existing project without replacing code, configuration, assets or tests', async () => {
    const fixture = await setup();
    await mkdir(fixture.workspace);
    const files = ['main.ts', 'authored-config.json', 'art.svg', 'controls.test.ts'];
    for (const file of files) await writeFile(path.join(fixture.workspace, file), `existing ${file}`);
    fixture.providerBuild.mockImplementationOnce(async input => {
      for (const file of files) expect(await readFile(path.join(input.workspace, file), 'utf8')).toBe(`existing ${file}`);
      return { threadId: 'fixture-thread', verificationMode: 'full', metrics: { provider: 'fixture', model: 'fixture', calls: 1 } };
    });

    const result = await fixture.run();

    expect(fixture.create).not.toHaveBeenCalled();
    expect(fixture.apply).not.toHaveBeenCalled();
    expect(fixture.importAssets).not.toHaveBeenCalled();
    expect(fixture.providerBuild).toHaveBeenCalledWith(expect.objectContaining({ assetSource: fixture.assetSource }));
    expect(fixture.verify).toHaveBeenCalledOnce();
    expect(fixture.buildWeb).toHaveBeenCalledOnce();
    expect(result.report.verification).toContain('workspace:continued');
    expect(await readdir(path.dirname(fixture.workspace))).toEqual(['game', 'generated-assets']);
  });

  it.each(['missing', 'empty'])('initializes a %s workspace once', async presence => {
    const fixture = await setup();
    if (presence === 'empty') await mkdir(fixture.workspace);
    const first = await fixture.run();
    const second = await fixture.run();
    expect(fixture.create).toHaveBeenCalledOnce();
    expect(fixture.apply).toHaveBeenCalledOnce();
    expect(fixture.importAssets).toHaveBeenCalledOnce();
    expect(first.report.verification).toContain('workspace:initialized');
    expect(second.report.verification).toContain('workspace:continued');
  });

  it('retains partial Builder work after a model failure and resumes from those bytes', async () => {
    const fixture = await setup();
    fixture.providerBuild.mockImplementationOnce(async input => {
      await writeFile(path.join(input.workspace, 'implemented-control.ts'), '// completed before interruption');
      throw new Error('model execution interrupted');
    });
    await expect(fixture.run()).rejects.toThrow('model execution interrupted');
    fixture.providerBuild.mockImplementationOnce(async input => {
      expect(await readFile(path.join(input.workspace, 'implemented-control.ts'), 'utf8')).toBe('// completed before interruption');
      return { threadId: 'resumed', verificationMode: 'full', metrics: { provider: 'fixture', model: 'fixture', calls: 1 } };
    });
    await fixture.run();
    expect(fixture.create).toHaveBeenCalledOnce();
    expect(fixture.apply).toHaveBeenCalledOnce();
    expect(fixture.verify).toHaveBeenCalledOnce();
  });

  it('still propagates verification failures instead of treating existing files as success', async () => {
    const fixture = await setup();
    await mkdir(fixture.workspace);
    await writeFile(path.join(fixture.workspace, 'partial.txt'), 'not yet valid');
    fixture.verify.mockRejectedValueOnce(new Error('existing project test failed'));
    await expect(fixture.run()).rejects.toThrow('existing project test failed');
    expect(fixture.create).not.toHaveBeenCalled();
    expect(fixture.buildWeb).not.toHaveBeenCalled();
  });

  it.each(['workspace', 'parent'])('rejects an existing %s symlink before calling any writer', async linkedPart => {
    const fixture = await setup();
    const foreign = path.join(fixture.root, 'foreign');
    await mkdir(foreign);
    await writeFile(path.join(foreign, 'sentinel'), 'untouched');
    if (linkedPart === 'workspace') await symlink(foreign, fixture.workspace);
    else {
      await rm(path.dirname(fixture.workspace), { recursive: true });
      await mkdir(path.join(foreign, 'game'));
      await writeFile(path.join(foreign, 'game/partial.txt'), 'untouched');
      await symlink(foreign, path.dirname(fixture.workspace));
    }
    await expect(fixture.run()).rejects.toThrow(/symlink/u);
    expect(fixture.create).not.toHaveBeenCalled();
    expect(fixture.providerBuild).not.toHaveBeenCalled();
    expect(await readFile(path.join(foreign, 'sentinel'), 'utf8')).toBe('untouched');
  });
});
